// Writes typed `as const` ABIs for the keeper and the frontend from Hardhat artifacts.
//   npm run build && node scripts/export-abis.js
const fs = require("fs")
const path = require("path")

const art = (p) => JSON.parse(fs.readFileSync(path.join(__dirname, "..", "artifacts", "contracts", p), "utf8")).abi
const abis = {
  parFactoryAbi: art("ParFactory.sol/ParFactory.json"),
  parVaultAbi: art("ParVault.sol/ParVault.json"),
  parCircuitAbi: art("ParCircuit.sol/ParCircuit.json"),
  mockPriceFeedAbi: art("mocks/MockMUSDSystem.sol/MockPriceFeed.json"),
}

let out = "// Generated by contracts/scripts/export-abis.js. Do not edit.\n\n"
for (const [name, abi] of Object.entries(abis)) {
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
for (const dest of ["../../keeper/src/abi.ts", "../../web/lib/abi.ts"]) {
  const file = path.join(__dirname, dest)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, out)
  console.log("wrote", path.relative(process.cwd(), file))
}
